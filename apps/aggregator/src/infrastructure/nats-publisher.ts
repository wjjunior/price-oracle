/**
 * @file NATS adapter for `PublishPort`.
 *
 * **What this is.** The "out" side of the aggregator's NATS plumbing.
 * Where `nats-source-stream.ts` subscribes to `ticks.>` (in), this
 * file publishes computed aggregates on `aggregates.<asset>` (out).
 *
 * **Why this adapter is thin.** Unlike the ingestor's
 * `NatsService` (which owns the connection lifecycle), this adapter
 * receives a **pre-connected `NatsConnection`** from the DI factory
 * in `app.module.ts`. The aggregator owns its own connection (one
 * for both publish and subscribe) and shares it between the two
 * adapters. That is why this file has no `OnModuleInit` / `connect()`
 * — it does one job: serialize, attach the correlation header,
 * publish.
 *
 * **Correlation header propagation.** Each call attaches the per-pulse
 * `correlationId` (generated by the orchestrator in `pulseAsset`) to
 * the NATS message header named `CORRELATION_HEADER` (defined in
 * `@price-oracle/contracts/subjects`). That header is what the SSE
 * controller — or any downstream consumer — would read to bind the
 * ID to its own log context. CLAUDE.md operational quirks:
 * "Correlation IDs propagate end-to-end via NATS message headers
 * (ingestor → aggregator) and SSE envelopes (aggregator → dashboard)."
 *
 * **Fail-safe.** Publish failures log `warn` and return. The
 * port contract says we never throw to the orchestrator
 * (`publish.port.ts`), and CLAUDE.md rule 20 maps "recoverable
 * boundary failures" to `warn`. NATS Core's fire-and-forget semantics
 * (`decisions.md` Entry 2) make a one-pulse drop acceptable — the
 * next 500ms pulse will publish fresh data.
 *
 * **`new headers()` per call is intentional.** The NATS client
 * mutates the headers object on send (`Sl` flag etc.); sharing a
 * single instance across publishes would intermix headers. The
 * allocation cost is trivial (a `Map`-like wrapper) compared to the
 * JSON serialization.
 *
 * Cross-references:
 *  - `domain/ports/publish.port.ts`: the port contract.
 *  - `@price-oracle/contracts/subjects.ts`: `aggregatesSubject(asset)`
 *    and `CORRELATION_HEADER`.
 *  - `packages/ingestor-transport/src/nats/nats.service.ts`: the
 *    sibling publish-side adapter the ingestors use; shares the same
 *    correlation-header contract.
 *  - `application/orchestrator.ts::publishAggregate`: the only caller.
 */
import { headers, type NatsConnection } from '@nats-io/nats-core';
import { CORRELATION_HEADER, aggregatesSubject } from '@price-oracle/contracts/subjects';


import type { PublishPort } from '../domain/ports/publish.port.js';
import type { AggregatePrice } from '../domain/types.js';
import type { Logger } from 'pino';

export class NatsPublisher implements PublishPort {
  /**
   * Single encoder instance reused across publishes — `TextEncoder`
   * is allocation-free to reuse and we encode once per pulse per
   * asset. Same pattern as the ingestor's `NatsService`.
   */
  private readonly encoder = new TextEncoder();

  constructor(
    private readonly connection: NatsConnection,
    private readonly logger: Logger,
  ) {}

  /**
   * Serialize the aggregate, attach the correlation header, publish.
   *
   * The subject is computed from the aggregate's own asset
   * (`aggregatesSubject('btc') === 'aggregates.btc'`). Per-asset
   * subjects are part of the system-wide first-class-asset principle
   * (CLAUDE.md operational quirks) and they are what enables
   * downstream subscribers (today: the dashboard; later: any
   * consumer) to filter by asset at the broker level.
   *
   * The `try/catch` is the safety net for the synchronous-throw case
   * (`connection.publish` can throw on a socket in a failed state).
   * Async errors from the NATS client are surfaced via the
   * subscription's error callback, not from this call site.
   */
  async publishAggregate(aggregate: AggregatePrice, correlationId: string): Promise<void> {
    const subject = aggregatesSubject(aggregate.asset);
    const messageHeaders = headers();
    messageHeaders.append(CORRELATION_HEADER, correlationId);
    try {
      this.connection.publish(subject, this.encoder.encode(JSON.stringify(aggregate)), {
        headers: messageHeaders,
      });
    } catch (err) {
      this.logger.warn(
        {
          event: 'publisher.failed',
          subject,
          correlationId,
          error: err instanceof Error ? err.message : String(err),
        },
        'Aggregate publish failed',
      );
    }
  }
}
